from playwright.sync_api import sync_playwright, expect

BASE = Path(__file__).resolve().parents[1]
OPTIONS = None


class Prototype(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.pw = sync_playwright().start()
        cls.browser = cls.pw.chromium.launch(channel=OPTIONS.channel)
        print(f"Navegador {cls.browser.version} · {OPTIONS.channel}")

    @classmethod
    def tearDownClass(cls):
        cls.browser.close()
        cls.pw.stop()

    def setUp(self):
        self.ctx = self.browser.new_context(offline=True, viewport={"width": 1600, "height": 900})
        self.page = self.ctx.new_page()
        self.errors = []
        self.remote = []
        self.page.on("pageerror", lambda error: self.errors.append(str(error)))
        self.page.on("request", lambda req: self.remote.append(req.url) if req.url.startswith(("http:", "https:", "ws:", "wss:")) else None)
        self.page.set_default_timeout(4500)
        self.page.goto((BASE / "index.html").as_uri())
        self.main = self.page.locator("main")

    def tearDown(self):
        self.ctx.close()
        self.assertEqual(self.errors, [])
        self.assertEqual(self.remote, [])

    def action(self, key):
        return self.page.locator(f'[data-act="{key}"]').first

    def click(self, key):
        self.action(key).click()

    def control(self, key):
        return self.page.locator(f'[data-change="{key}"]')

    def choose(self, key, value):
        self.control(key).select_option(str(value))

    def number(self, key, value):
        el = self.control(key)
        el.fill(str(value))
        el.press("Tab")

    def navigate(self, key):
        if self.page.evaluate("innerWidth < 900") and not self.page.locator("body").evaluate("e=>e.classList.contains('menu-open')"):
            self.click("menu")
        self.click("go:" + key)

    def contains(self, *texts):
        for text in texts:
            expect(self.main).to_contain_text(text)

    def shot(self, name):
        if OPTIONS.capture:
            (BASE / "review").mkdir(exist_ok=True)
            self.page.evaluate("window.scrollTo(0,0)")
            self.page.screenshot(path=BASE / "review" / (name + ".png"), animations="disabled")

